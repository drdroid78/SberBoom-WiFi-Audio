import ru.drdroid78.sberboom.protocol.*
import ru.drdroid78.sberboom.audio.*
fun main() {
    var n = 0
    fun verify(label: String, passed: Boolean) { check(passed) { label }; println("PASS $label"); n++ }
    verify("malformed JWT", TokenPolicy.error(null,null,"bad",100) != null)
    verify("invalid algorithm", TokenPolicy.error("none",200,null,100) != null)
    verify("no expiry", TokenPolicy.error("RS256",null,null,100) != null)
    verify("expiry boundary", TokenPolicy.error("RS256",100,null,100) != null)
    verify("valid format only", TokenPolicy.error("RS256",101,null,100) == null)
    val star = Tlv.decode(Protocol.starCommandAudioStart("m","s","u","{}",0))
    verify("matching start response", StreamReplyPolicy.matches(star,"m","s"))
    verify("different master", !StreamReplyPolicy.matches(star,"other","s"))
    verify("different session", !StreamReplyPolicy.matches(star,"m","other"))
    verify("no reply", !StreamReplyPolicy.matches(null,"m","s"))
    verify("dead message", !StreamReplyPolicy.matches(Tlv.decode(Protocol.starCommandAudioDead("m","s","u")),"m","s"))
    val a=byteArrayOf(8,1);val b=byteArrayOf(8,2)
    val decoded = Tlv.decodeRepeated(Protocol.startStreaming("{}",55,listOf(a,b)))
    verify("timestamp", decoded[2]?.single()==55L)
    verify("repeated masters", (decoded[3]?.get(0) as ByteArray).contentEquals(a) && (decoded[3]?.get(1) as ByteArray).contentEquals(b))
    verify("start lead time",Protocol.StartStreamingTiming.monoTimestampMs(50_000)==50_410L)
    verify("PTP micros to StartStreaming millis",Protocol.StartStreamingTiming.offsetMs(-1_234_567)==-1_234L)
    val measuredMaster=Protocol.syncedMaster("source",-1_234)
    val measuredFields=Tlv.decode(measuredMaster)
    verify("measured master ID",measuredFields.str(1)=="source")
    verify("signed offset wire",measuredFields.long(2)==-1_234L)
    val measuredStart=Tlv.decodeRepeated(Tlv.decode(Protocol.starCommandAudioStart("source","mr","source","{}",50_410,listOf(measuredMaster))).nested(Protocol.STAR_FIELD_AUDIO_STREAM)!!.bytes(Protocol.AUDIO_START_STREAMING)!!)
    verify("measured master repeated field",measuredStart[3]?.size==1 && (measuredStart[3]!!.single() as ByteArray).contentEquals(measuredMaster))
    val packet=UdpPacket.build(-1,0x1ffffffffL,byteArrayOf(9,8))
    verify("sequence wrap", UdpPacket.sequence(packet)==-1)
    verify("timestamp wrap", UdpPacket.timestamp(packet)==0xffffffffL)
    verify("Opus payload", UdpPacket.payload(packet).contentEquals(byteArrayOf(9,8)))
    verify("20ms Opus", OpusPacket.samplesAt48k(byteArrayOf((31 shl 3).toByte()))==960)
    val sync=StarPtpPacket.encode(StarPtpPacket.Type.SYNC, micros=0x0102030405060708L)
    verify("PTP sync wire", sync.contentEquals(byteArrayOf(0x10,0,0,8,7,6,5,4,3,2,1)))
    val req=StarPtpPacket.encode(StarPtpPacket.Type.DELAY_REQUEST,0xabcd)
    verify("PTP delay request wire", req.contentEquals(byteArrayOf(0x11,0xcd.toByte(),0xab.toByte())))
    val resp=StarPtpPacket.encode(StarPtpPacket.Type.DELAY_RESPONSE,0xabcd,0x0102030405060708L)
    verify("PTP delay response wire", resp.contentEquals(byteArrayOf(0x12,0xcd.toByte(),0xab.toByte(),8,7,6,5,4,3,2,1)))
    verify("PTP unsigned sequence", StarPtpPacket.decode(req)?.sequence==0xabcd)
    verify("PTP timestamp LE", StarPtpPacket.decode(resp)?.micros==0x0102030405060708L)
    verify("PTP rejects short reply", StarPtpPacket.decode(resp.copyOf(3))==null)
    verify("PTP rejects unknown type", StarPtpPacket.decode(byteArrayOf(0x13,0,0))==null)
    verify("PTP request has no timestamp", StarPtpPacket.decode(req)?.micros==null)
    val ackEnvelope = Tlv.decode(Tlv.concat(Tlv.fieldVarint(1,3),Tlv.fieldString(2,"request-1"),Tlv.fieldBytes(6,byteArrayOf())))
    verify("StarCommand default ACK", StreamReplyPolicy.parseAck(ackEnvelope,"request-1",8)?.accepted == true)
    verify("StarCommand mismatched id", StreamReplyPolicy.parseAck(ackEnvelope,"other",8)==null)
    verify("StarCommand error ACK", StreamReplyPolicy.parseAck(ackEnvelope + (3 to 5L),"request-1",8)?.accepted == false)
    verify("StarCommand rejects request", StreamReplyPolicy.parseAck(ackEnvelope + (10 to 1L),"request-1",8)==null)
    verify("StarCommand requires response field", StreamReplyPolicy.parseAck(ackEnvelope - 6,"request-1",8)==null)
    verify("media default success", Protocol.parsePlayerStatus(Tlv.decode(Tlv.fieldBytes(16,byteArrayOf())))==0L)
    verify("media unsupported", Protocol.parsePlayerStatus(Tlv.decode(Tlv.fieldBytes(16,Tlv.fieldVarint(1,1))))==1L)
    verify("media missing response", Protocol.parsePlayerStatus(emptyMap())==null)
    verify("volume empty acknowledgement", Protocol.parseVolumeAck(Tlv.decode(Tlv.fieldBytes(14,Tlv.fieldBytes(1,byteArrayOf()))))==1L)
    verify("volume rejects numeric status", Protocol.parseVolumeAck(Tlv.decode(Tlv.fieldBytes(14,Tlv.fieldVarint(1,1))))==null)
    val metaBytes=Tlv.concat(Tlv.fieldVarint(5,1),Tlv.fieldString(9,"{\"md\":\"MULTIROOM\"}"),Tlv.fieldVarint(10,2),Tlv.fieldString(14,"{}"))
    val metaReply=Tlv.decode(Tlv.fieldBytes(10,Tlv.concat(Tlv.fieldVarint(1,1),Tlv.fieldBytes(2,metaBytes))))
    val meta=Protocol.parseMetaData(metaReply)
    verify("group metadata fields", meta?.multiroomSupported==true && meta.deviceGroupServiceVersion==2L && meta.deviceGroupInfoJson=="{}" && meta.multiroomInfoJson?.contains("MULTIROOM")==true)
    verify("metadata rejected status", Protocol.parseMetaData(Tlv.decode(Tlv.fieldBytes(10,Tlv.fieldBytes(2,metaBytes))))==null)
    verify("multiroom exact wire", Protocol.mediaCommand(Protocol.MEDIA_START_MULTIROOM).contentEquals(byteArrayOf(0x82.toByte(),1,2,8,8)))
    val gate=SessionGate()
    val t1=gate.begin()!!
    verify("exclusive start", gate.begin()==null)
    verify("stop before StartStreaming", gate.requestStop(t1) && !gate.activate(t1) && !gate.shouldSendStop(t1))
    verify("cannot start during cleanup", gate.begin()==null)
    verify("finish cancelled startup", gate.finish(t1))
    val t2=gate.begin()!!
    verify("stale stop cannot affect new session", !gate.requestStop(t1) && gate.isStarting(t2))
    verify("remote start attempt recorded", gate.markStartSent(t2) && gate.shouldSendStop(t2))
    verify("uncertain ACK requires stop", gate.requestStop(t2) && gate.shouldSendStop(t2))
    verify("late ACK cannot activate cancelled session", !gate.activate(t2))
    verify("finish uncertain session", gate.finish(t2))
    val t3=gate.begin()!!
    verify("active session", gate.markStartSent(t3) && gate.activate(t3) && gate.isActive(t3))
    verify("shutdown cannot start another session", gate.close()==t3 && gate.finish(t3) && gate.begin()==null)
    val clock=StarPtpClock(maxAgeUs=10000,minSamples=3)
    repeat(3) { k ->
        val t=k*1000L
        clock.onSync(t,t+1050) // local ahead by 1000 us, propagation 50 us
        clock.onDelayRequest(k,t+1200)
        verify("PTP wrong sequence $k", !clock.onDelayResponse(k+1,t+250,t+1300))
        verify("PTP valid sample $k", clock.onDelayResponse(k,t+250,t+1300))
        verify("PTP replay rejected $k", !clock.onDelayResponse(k,t+250,t+1300))
    }
    val est=clock.estimate(3400)
    verify("PTP offset",est?.localMinusRemoteUs==1000L)
    verify("PTP propagation",est?.pathDelayUs==50L)
    verify("PTP remote to local",est?.remoteToLocal(2000)==3000L)
    verify("PTP sample expiration",clock.estimate(20000)==null)
    val loop=java.net.InetAddress.getLoopbackAddress()
    val left=java.net.DatagramSocket(java.net.InetSocketAddress(loop,0))
    val right=java.net.DatagramSocket(java.net.InetSocketAddress(loop,0))
    val errors=java.util.concurrent.CopyOnWriteArrayList<Exception>()
    val pa=StarPtpPeer(left,java.net.InetSocketAddress(loop,right.localPort),{System.nanoTime()/1000 + 100_000},50_000,errors::add)
    val pb=StarPtpPeer(right,java.net.InetSocketAddress(loop,left.localPort),{System.nanoTime()/1000},50_000,errors::add)
    try {
        pa.start();pb.start()
        val deadline=System.nanoTime()+4_000_000_000L
        while ((pa.estimate()==null || pb.estimate()==null) && System.nanoTime()<deadline) Thread.sleep(30)
        val ea=pa.estimate();val eb=pb.estimate()
        verify("real UDP PTP two-way samples",ea!=null && eb!=null)
        verify("real UDP PTP clock offset",kotlin.math.abs(ea!!.localMinusRemoteUs-100_000)<15_000 && kotlin.math.abs(eb!!.localMinusRemoteUs+100_000)<15_000)
        verify("real UDP PTP no transport errors", errors.isEmpty())
    } finally { pa.close();pb.close() }
    verify("PTP sockets closed",left.isClosed && right.isClosed)
    println("$n assertions passed; pure Kotlin/JVM, not Android or hardware")
}
